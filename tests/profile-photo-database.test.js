import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {PGlite} from '@electric-sql/pglite';

test('private photo SQL isolates account objects, including under unrelated broad policies', async t => {
 const db = new PGlite(); t.after(() => db.close());
 const a='11111111-1111-4111-8111-111111111111'; const b='22222222-2222-4222-8222-222222222222';
 await db.exec(`create role anon; create role authenticated; create schema auth; create schema storage;
 create function auth.uid() returns uuid language sql stable as $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
 create table storage.buckets(id text primary key, name text, public boolean, file_size_limit bigint, allowed_mime_types text[]);
 create table storage.objects(bucket_id text, name text, primary key(bucket_id,name));
 alter table storage.objects enable row level security;
 grant usage on schema auth,storage to anon,authenticated;
 grant execute on function auth.uid() to anon,authenticated;
 grant select,insert,update,delete on storage.objects to anon,authenticated;`);
 const sql = await readFile(new URL('../supabase/002_fotos_de_perfil.sql',import.meta.url),'utf8');
 await db.exec(sql);
 const login=async(id, role='authenticated')=>{ await db.exec('reset role'); await db.query("select set_config('request.jwt.claim.sub',$1,false)",[id]); await db.exec(`set role ${role}`); };
 const insert=(id,bucket='caderno-profile-photos')=>db.query('insert into storage.objects values ($1,$2)',[bucket,`${id}/profile.webp`]);
 const rows=()=>db.query("select * from storage.objects where bucket_id='caderno-profile-photos'");
 await login(a); await insert(a);
 await assert.rejects(insert(b),error=>error.code==='42501');
 await login(b); assert.equal((await rows()).rows.length,0); await insert(b);
 assert.equal((await db.query('delete from storage.objects where name=$1 returning name',[`${a}/profile.webp`])).rows.length,0);
 await assert.rejects(db.query('update storage.objects set name=$1 where name=$2',[`${a}/profile.webp`,`${b}/profile.webp`]),error=>error.code==='42501');
 await db.exec('reset role; create policy unrelated_broad_policy on storage.objects for all to public using(true) with check(true);');
 await login(b); assert.deepEqual((await rows()).rows.map(row=>row.name),[`${b}/profile.webp`]);
 await assert.rejects(insert('foreign-id'),error=>error.code==='42501');
 await insert('unrelated','other-bucket');
 await login('', 'anon'); assert.equal((await rows()).rows.length,0);
 await assert.rejects(insert(a),error=>error.code==='42501');
 await db.exec('reset role'); await db.exec(sql);
 assert.equal((await rows()).rows.length,2);
 const bucket=(await db.query("select * from storage.buckets where id='caderno-profile-photos'")).rows[0];
 assert.equal(bucket.public,false); assert.equal(Number(bucket.file_size_limit),2097152);
 assert.deepEqual(bucket.allowed_mime_types,['image/jpeg','image/png','image/webp']);
 await login(a); assert.equal((await db.query('delete from storage.objects where name=$1 returning name',[`${a}/profile.webp`])).rows.length,1);
});
